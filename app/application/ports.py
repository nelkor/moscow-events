from typing import Any, Protocol
from uuid import UUID


class Repository(Protocol):
    def lock_catalog(self) -> None: ...
    def get(self, resource: str, identifier: UUID, lock: bool = False) -> Any: ...
    def save(self, resource: str, entity) -> None: ...
    def delete(self, resource: str, identifier: UUID) -> None: ...
    def sold(self, event_id: UUID) -> int: ...
    def cancel_reservations(self, event_id: UUID) -> None: ...
    def referenced(self, resource: str, identifier: UUID) -> bool: ...
    def max_quota(self, venue_id: UUID) -> int: ...
    def idempotency_get(self, scope: str, key: str, fingerprint: str) -> dict | None: ...
    def idempotency_save(self, scope: str, key: str, fingerprint: str, response: dict) -> None: ...


class Queries(Protocol):
    def detail(self, resource: str, identifier: UUID, include: str = "") -> dict: ...
    def listing(self, resource: str, filters: dict) -> dict: ...
    def geojson(self, resource: str, filters: dict) -> dict: ...
    def analytics(self, resource: str, filters: dict) -> dict: ...
    def metadata(self) -> dict: ...
    def summary(self) -> dict: ...


class UnitOfWork(Protocol):
    repository: Repository
    queries: Queries

    def commit(self) -> None: ...
    def rollback(self) -> None: ...
    def savepoint(self) -> Any: ...
